export const CATEGORY_LABELS: Record<Locale, CategoryLabels> = { es, en, pt };

/**
 * Etiqueta localizada de una categoría.
 *
 * `fallback` es el `name` que manda el backend (es-DO): se usa cuando el nodo no tiene key (los de
 * nivel ≥2 no vienen del markdown) o cuando la key todavía no está traducida. Nunca devuelve vacío
 * — una categoría sin traducir se ve en español, que es mucho mejor que un hueco en la UI.
 */
export function categoryLabel(
  key: string | null | undefined,
  fallback: string,
  locale: Locale = DEFAULT_LOCALE,
): string {
  if (!key) return fallback;
  return CATEGORY_LABELS[locale]?.[key] ?? CATEGORY_LABELS[DEFAULT_LOCALE][key] ?? fallback;
}
